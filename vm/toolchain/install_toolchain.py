#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成 arm-linux-gnueabihf 交叉编译工具链包装器（后端 = zig 自带 clang/llvm）。
安装位置: C:\\Users\\38368\\toolchain\\arm-linux-gnueabihf
"""
import os
import stat

TC = r"C:\Users\38368\toolchain\arm-linux-gnueabihf"
BIN = os.path.join(TC, "bin")
ZIG = r"C:\Users\38368\miniconda3\lib\site-packages\ziglang\zig.exe"
ZIG_POSIX = "/c/Users/38368/miniconda3/lib/site-packages/ziglang/zig.exe"
WS = r"C:\Users\38368\OneDrive\文档\deepseek-harness\default-workspace"

# 默认目标：ARMv7 硬浮点 glibc 2.23（老 rootfs 也能跑，新 rootfs 向上兼容）
TARGET_GLIBC = "arm-linux-gnueabihf.2.23"
TARGET_MUSL = "arm-linux-musleabihf"

TOOLS = {
    # 名字: (zig 子命令, 额外默认参数)
    "gcc": ("cc", f"-target {TARGET_GLIBC}"),
    "cc": ("cc", f"-target {TARGET_GLIBC}"),
    "g++": ("c++", f"-target {TARGET_GLIBC}"),
    "c++": ("c++", f"-target {TARGET_GLIBC}"),
    "ar": ("ar", ""),
    "ranlib": ("ranlib", ""),
    "gcc-static": ("cc", f"-target {TARGET_MUSL} -static"),
    "g++-static": ("c++", f"-target {TARGET_MUSL} -static"),
}

CMD_TMPL = """@echo off
rem generated by install_toolchain.py  --  backend: zig clang
setlocal
set "ZIG={zig}"
if not exist "%ZIG%" (
  echo [x] zig not found: %ZIG%
  echo     run: python -m pip install ziglang
  exit /b 1
)
"%ZIG%" {sub} {flags} %*
exit /b %ERRORLEVEL%
"""

SH_TMPL = """#!/bin/bash
# generated by install_toolchain.py  --  backend: zig clang
exec "{zig}" {sub} {flags} "$@"
"""

READELF_CMD = """@echo off
setlocal
python "{ws}\\elf_info.py" %*
exit /b %ERRORLEVEL%
"""

ENV_CMD = """@echo off
rem 把这个工具链加进当前 cmd/powershell 的 PATH
set "PATH={bin};%PATH%"
echo [ok] arm-linux-gnueabihf toolchain in PATH
arm-linux-gnueabihf-gcc --version
"""

ENV_SH = f"""# source 这个文件把工具链加进 PATH
export PATH="{BIN.replace(chr(92), '/')}:$PATH"
echo "[ok] arm-linux-gnueabihf toolchain in PATH"
"""

README = f"""# arm-linux-gnueabihf 交叉工具链（Windows 宿主）
后端：zig 自带的 clang/LLVM 交叉编译能力（无需 WSL / 无需管理员 / 无需装 Ubuntu）
位置：{TC}\\bin

## 用法（cmd / PowerShell，先 source 一次环境）
    {TC}\\tc-env.cmd
    arm-linux-gnueabihf-gcc -O2 -o hello hello.c
    arm-linux-gnueabihf-g++ -O2 -o app main.cpp

## 目标三元组预设
    arm-linux-gnueabihf-gcc          -> arm-linux-gnueabihf.2.23   动态链接 glibc 2.23（默认，兼容老 rootfs）
    arm-linux-gnueabihf-gcc-static   -> arm-linux-musleabihf -static  静态，libc 打包进二进制，换任何 ARMv7 Linux 都能跑

## 常用附加参数
    -mcpu=cortex_a7 -mfpu=neon-vfpv4 -mfloat-abi=hard   针对 i.MX6ULL 优化
    -s                                                   链接后 strip，减小体积
    -shared -fPIC                                        编 .so

## 查看产物架构
    arm-linux-gnueabihf-readelf hello
    （等价：python {WS}\\elf_info.py hello）

## 注意
* 动态链接版本的二进制依赖板子上的 glibc 版本。板子上先跑 `ldd --version` 或
  `ls -l /lib/libc-*.so*`；若报 "GLIBC_2.xx not found"，改用 -static 版本，或把
  gcc.cmd 里的 .2.23 改成更低的版本号（zig 支持 2.17 / 2.23 / 2.28 / 2.34 等）。
* 编译内核模块需要内核源码树 + 真正的 gcc 插件机制，本工具链只适合用户态程序。
"""


def main():
    os.makedirs(BIN, exist_ok=True)
    made = []
    for name, (sub, flags) in TOOLS.items():
        full = f"arm-linux-gnueabihf-{name}"
        cmd_path = os.path.join(BIN, full + ".cmd")
        with open(cmd_path, "w", encoding="utf-8", newline="\r\n") as f:
            f.write(CMD_TMPL.format(zig=ZIG, sub=sub, flags=flags))
        made.append(cmd_path)
        sh_path = os.path.join(BIN, full)
        with open(sh_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(SH_TMPL.format(zig=ZIG_POSIX, sub=sub, flags=flags))
        os.chmod(sh_path, os.stat(sh_path).st_mode | stat.S_IEXEC)
        made.append(sh_path)

    for p, body in [
        (os.path.join(BIN, "arm-linux-gnueabihf-readelf.cmd"), READELF_CMD.format(ws=WS)),
        (os.path.join(TC, "tc-env.cmd"), ENV_CMD.format(bin=BIN)),
        (os.path.join(TC, "tc-env.sh"), ENV_SH),
        (os.path.join(TC, "README.md"), README),
    ]:
        with open(p, "w", encoding="utf-8", newline="\r\n" if p.endswith(".cmd") else "\n") as f:
            f.write(body)
        made.append(p)

    # 自检
    print(f"生成 {len(made)} 个文件 -> {BIN}")
    for m in made:
        print("  ", m)


if __name__ == "__main__":
    main()
